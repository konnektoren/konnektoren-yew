use crate::i18n::use_i18n;
use konnektoren_yew_core::{FilteredList, ListItem, ListLabels};
use serde::{Deserialize, Serialize};
use yew::prelude::*;

#[derive(Debug, Serialize, Deserialize)]
struct License {
    expression: String,
}

#[derive(Debug, Serialize, Deserialize)]
struct Component {
    name: String,
    version: String,
    #[serde(default)]
    licenses: Option<Vec<License>>,
}

#[derive(Debug, Serialize, Deserialize)]
struct CycloneDX {
    #[serde(default)]
    components: Vec<Component>,
}

#[derive(Properties, PartialEq, Default)]
pub struct AppDependenciesProps {
    /// CycloneDX JSON generated by the host application.
    #[prop_or_default]
    pub sbom_json: Option<AttrValue>,
}

#[function_component(AppDependenciesComponent)]
pub fn app_dependencies(props: &AppDependenciesProps) -> Html {
    let i18n = use_i18n();
    let sbom = use_memo(props.sbom_json.clone(), |provided| {
        let json = provided
            .as_ref()
            .map(|json| json.as_str())
            .unwrap_or(env!("CARGO_SBOM"));
        serde_json::from_str::<CycloneDX>(json).unwrap_or_else(|error| {
            tracing::warn!("Failed to parse dependency inventory: {error}");
            CycloneDX { components: vec![] }
        })
    });

    let filter = use_state(String::new);
    let show_list = use_state(|| false);

    let mut license_count = std::collections::BTreeMap::new();
    for component in &sbom.components {
        for license in component.licenses.iter().flatten() {
            *license_count.entry(&license.expression).or_insert(0) += 1;
        }
    }

    let query = filter.to_lowercase();
    let items: Vec<ListItem> = sbom.components.iter().enumerate()
        .filter(|(_, component)| component.name.to_lowercase().contains(&query))
        .map(|(index, component)| ListItem::new(index.to_string(), html! {
            <div class="app-dependencies__item">
                <span class="app-dependencies__name">{&component.name}{" "}{&component.version}</span>
                <span class="app-dependencies__item-licenses">
                    {if let Some(licenses) = &component.licenses {
                        html! { <>{for licenses.iter().map(|license| html! {
                            <span class="license-badge license-badge--small">{&license.expression}</span>
                        })}</> }
                    } else {
                        html! { <span class="license-badge license-badge--small">{i18n.t("Unknown")}</span> }
                    }}
                </span>
            </div>
        })).collect();
    let matching = items.len();
    let on_search = {
        let filter = filter.clone();
        Callback::from(move |value| filter.set(value))
    };
    let on_clear = {
        let filter = filter.clone();
        Callback::from(move |()| filter.set(String::new()))
    };
    let labels = ListLabels {
        search: i18n.t("Search dependencies...").into(),
        search_placeholder: i18n.t("Search dependencies...").into(),
        noun: i18n.t("Dependencies").into(),
        list: i18n.t("Dependencies").into(),
        empty: i18n.t("Nothing here yet.").into(),
        no_match: i18n.t("Nothing matches these filters.").into(),
        sort_by: i18n.t("Sort by").into(),
        show: i18n.t("Show").into(),
        clear: i18n.t("Clear filters").into(),
        show_more: i18n.t("Show more").into(),
    };

    let toggle_list = {
        let show_list = show_list.clone();
        Callback::from(move |_| {
            show_list.set(!*show_list);
        })
    };

    html! {
        <div class="app-dependencies">
            <div class="app-dependencies__summary">
                <div class="app-dependencies__header">
                    <span class="app-dependencies__count">
                        {format!("{} {}", sbom.components.len(), i18n.t("Dependencies"))}
                    </span>
                    <button class="app-dependencies__toggle" onclick={toggle_list}>
                        {if *show_list { i18n.t("Hide List") } else { i18n.t("Show List") }}
                    </button>
                </div>
                <div class="app-dependencies__licenses">
                    {for license_count.iter().map(|(license, count)| {
                        html! {
                            <span class="license-badge" >
                                {format!("{} ({})", license, count)}
                            </span>
                        }
                    })}
                </div>
            </div>
            if *show_list {
                <FilteredList class="app-dependencies__list" {labels} {items} {matching}
                    total={sbom.components.len()} search={(*filter).clone()}
                    active={!filter.is_empty()} {on_search} {on_clear} />
            }
        </div>
    }
}

