#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_host_inventory_with_optional_licenses() {
        let inventory: CycloneDX = serde_json::from_str(
            r#"{"components":[{"name":"example","version":"1.0","licenses":[{"expression":"MIT OR Apache-2.0"}]},{"name":"private","version":"2.0"}]}"#,
        ).unwrap();
        assert_eq!(inventory.components.len(), 2);
        assert_eq!(
            inventory.components[0].licenses.as_ref().unwrap()[0].expression,
            "MIT OR Apache-2.0"
        );
        assert!(inventory.components[1].licenses.is_none());
    }

    #[test]
    fn accepts_disabled_sbom_fallback() {
        let inventory: CycloneDX = serde_json::from_str("{}").unwrap();
        assert!(inventory.components.is_empty());
    }
}
